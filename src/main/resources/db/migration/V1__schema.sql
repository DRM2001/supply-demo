CREATE TABLE products (sku VARCHAR(40) PRIMARY KEY, name VARCHAR(120) NOT NULL);
CREATE TABLE suppliers (id BIGINT PRIMARY KEY, name VARCHAR(120) NOT NULL);
CREATE TABLE offers (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 version BIGINT NOT NULL DEFAULT 0,
 product_sku VARCHAR(40) NOT NULL REFERENCES products(sku),
 supplier_id BIGINT NOT NULL REFERENCES suppliers(id),
 region VARCHAR(20) NOT NULL CHECK (region IN ('MADRID','ANDALUCIA','CATALUNA')),
 unit_price NUMERIC(12,2) NOT NULL CHECK (unit_price > 0),
 stock INTEGER NOT NULL CHECK (stock >= 0 AND stock <= 1000000),
 lead_days INTEGER NOT NULL CHECK (lead_days >= 0 AND lead_days <= 365),
 CONSTRAINT uq_offer UNIQUE(product_sku,supplier_id,region)
);
CREATE INDEX idx_offers_lookup ON offers(product_sku,region,stock);
